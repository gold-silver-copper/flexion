//! Writing a model as Rust code: one module per part of speech under
//! `src/model/`, each implementing [`flexion::PosModel`]. The tree becomes
//! `match`es over the word's letters (read from its end), the edits and
//! classes become statics, the lexicon and the join prefixes become `match`es
//! on strings. The code is written from the in-memory [`Tables`] the trainer
//! scored, so the crate answers exactly as they do.
//!
//! Big models are split so rustc can compile them: a tree function holds at
//! most [`FN_NODES`] nodes (bigger subtrees are calls to functions of their
//! own), a file at most [`FILE_NODES`] nodes or [`FILE_ITEMS`] table entries.

use crate::spec::Language;
use flexion::tables::{Built, NodeKind, NodeRec, Tables};
use flexion::{BOUNDARY, INITIAL_TOKEN, NONE, SYLLABLE_TOKEN};
use std::collections::HashMap;
use std::fmt::Write as _;

/// Tree nodes one generated function holds at most.
const FN_NODES: usize = 256;
/// `match`es nested in one generated function at most: deeper nesting
/// overflows rustc's stack on long words' chains of nodes.
const MAX_NESTING: usize = 6;
/// Tree nodes one generated file holds at most.
const FILE_NODES: usize = 8192;
/// Table entries (edits, classes, lexicon words) one file holds at most.
const FILE_ITEMS: usize = 20_000;
/// Arms one generated string `match` holds at most: rustc lowers a match on
/// strings to a chain of tests and overflows its stack on long ones.
const MATCH_ARMS: usize = 500;

/// The files of `src/model/`: `(path under src/, contents)`.
pub fn generate(lang: &Language, built: &Built) -> Vec<(String, String)> {
    let tables = built.tables();
    let names = part_names(lang, tables);
    let mut files = Vec::new();
    let sp = built.spelling();
    let mut root = String::new();
    let _ = writeln!(
        root,
        "//! The {} model, generated by flexion-train from configs/src/{}.rs: one\n\
         //! module per part of speech (and per helper model), each a\n\
         //! [`flexion::PosModel`]. Don't edit by hand.\n",
        lang.display,
        lang.name.replace('-', "_")
    );
    root.push_str("use flexion::{Model, PosModel, Spelling, SpellingStrings};\n\n");
    for name in &names {
        let _ = writeln!(root, "mod {name};");
    }
    let s = |v: &str| format!("{v:?}");
    let _ = writeln!(
        root,
        "\nstatic STRINGS: SpellingStrings<'static> = SpellingStrings {{\n    \
         stress_marks: {},\n    stress_table: {},\n    vowels: {},\n    implicit: {},\n    \
         fold_from: {},\n    fold_to: {},\n    strip_marks: {},\n    unmark_from: {},\n    \
         unmark_to: {},\n    syllabic: {},\n    mute: {},\n    diphthongs: {},\n    hiatus: {},\n}};\n",
        s(&sp.stress_marks),
        s(&sp.stress_table),
        s(&sp.vowels),
        s(&sp.implicit),
        s(&sp.fold_from),
        s(&sp.fold_to),
        s(&sp.strip_marks),
        s(&sp.unmark_from),
        s(&sp.unmark_to),
        s(&sp.syllabic),
        s(&sp.mute),
        s(&sp.diphthongs),
        s(&sp.hiatus),
    );
    let _ = writeln!(
        root,
        "/// The model, in the config's order of parts of speech (helper models\n\
         /// after).\npub(crate) fn build() -> Model<'static> {{\n    Model::new(\n        \
         Spelling::new({}, {}, STRINGS),\n        vec![",
        sp.fold_case, sp.mark_monosyllables
    );
    for name in &names {
        let _ = writeln!(
            root,
            "            &{name}::{} as &dyn PosModel,",
            camel(name)
        );
    }
    root.push_str("        ],\n    )\n}\n");
    let with_laws: Vec<&String> = names
        .iter()
        .zip(tables)
        .filter(|(_, t)| t.phonology.is_some())
        .map(|(n, _)| n)
        .collect();
    if !with_laws.is_empty() {
        let checks: Vec<String> = with_laws
            .iter()
            .map(|n| format!("{n}::sound_laws_compile()"))
            .collect();
        let _ = writeln!(
            root,
            "\n/// Whether every part of speech's sound laws compile.\npub(crate) fn sound_laws_compile() -> bool {{\n    {}\n}}",
            checks.join(" && ")
        );
    }
    files.push(("model/mod.rs".to_string(), root));
    // The cells another part of speech derives its lemmas from.
    let mut lent: Vec<std::collections::BTreeSet<usize>> = vec![Default::default(); tables.len()];
    for t in tables {
        for (source, cells) in &t.lexicon_from {
            if let Some(l) = lent.get_mut(*source) {
                l.extend(cells);
            }
        }
    }
    for ((t, name), lent) in tables.iter().zip(&names).zip(&lent) {
        part(&mut files, &format!("model/{name}"), name, t, lent);
    }
    files
}

/// The files of [`generate`] as one file of inline modules, for
/// `include!` (the code-generation check compiles code generated at build
/// time this way).
pub fn single_file(files: &[(String, String)]) -> String {
    let by_path: HashMap<&str, &str> = files
        .iter()
        .map(|(p, c)| (p.as_str(), c.as_str()))
        .collect();
    inline(&by_path, "model", true)
}

/// Module `module`'s code with each `mod x;` replaced by `mod x { … }`.
fn inline(files: &HashMap<&str, &str>, module: &str, root: bool) -> String {
    let content = files
        .get(format!("{module}/mod.rs").as_str())
        .or_else(|| files.get(format!("{module}.rs").as_str()))
        .copied()
        .unwrap_or("");
    let mut out = String::with_capacity(content.len());
    for line in content.lines() {
        if let Some(name) = line.strip_prefix("mod ").and_then(|l| l.strip_suffix(';')) {
            let _ = writeln!(out, "mod {name} {{");
            out.push_str(&inline(files, &format!("{module}/{name}"), false));
            out.push_str("}\n");
        } else if root && line.starts_with("//!") {
            // `include!` takes no inner doc comments.
            let _ = writeln!(out, "//{}", line.trim_start_matches("//!"));
        } else {
            out.push_str(line);
            out.push('\n');
        }
    }
    out
}

/// Module names of the model's parts of speech: the config's, then each
/// helper model named after the part of speech it serves.
fn part_names(lang: &Language, tables: &[Tables]) -> Vec<String> {
    let mut names: Vec<Option<String>> = vec![None; tables.len()];
    let mut set = |i: usize, name: String| {
        if let Some(slot) = names.get_mut(i)
            && slot.is_none()
        {
            *slot = Some(name);
        }
    };
    for (i, p) in lang.parts.iter().enumerate() {
        set(i, ident(p.name));
    }
    for (p, t) in lang.parts.iter().zip(tables) {
        let base = ident(p.name);
        if let Some(r) = t.restore {
            set(r, format!("{base}_restore"));
        }
        if let Some(r) = t.restore_front {
            set(r, format!("{base}_restore_front"));
        }
        for &(cell, m) in &t.part_models {
            set(m, format!("{base}_from_cell_{cell}"));
        }
    }
    names
        .into_iter()
        .enumerate()
        .map(|(i, n)| n.unwrap_or_else(|| format!("part_{i}")))
        .collect()
}

fn ident(name: &str) -> String {
    name.chars()
        .map(|c| {
            if c.is_ascii_alphanumeric() {
                c.to_ascii_lowercase()
            } else {
                '_'
            }
        })
        .collect()
}

fn camel(name: &str) -> String {
    name.split('_')
        .map(|part| {
            let mut c = part.chars();
            c.next()
                .map(|f| f.to_uppercase().chain(c).collect::<String>())
                .unwrap_or_default()
        })
        .collect()
}

fn f(x: f32) -> String {
    format!("{x:?}")
}

/// One part of speech's module.
fn part(
    files: &mut Vec<(String, String)>,
    dir: &str,
    name: &str,
    t: &Tables,
    lent: &std::collections::BTreeSet<usize>,
) {
    let ty = camel(name);
    let wide = t.edits.len() >= usize::from(u16::MAX);
    let (id_ty, none) = if wide {
        ("u32", "u32::MAX")
    } else {
        ("u16", "u16::MAX")
    };
    let mut m = String::new();
    let _ = writeln!(
        m,
        "//! {name}: {} cells, {} edits, {} classes, {} tree nodes.\n",
        t.cells,
        t.edits.len(),
        t.classes.len(),
        t.nodes.len()
    );
    m.push_str("use flexion::{Class, Edit, Join, Path, PosModel, Walk};\n\n");
    m.push_str("mod classes;\nmod edits;\nmod tree;\n");
    let has_lexicon = !t.lexicon.is_empty();
    let has_joins = !t.joins.is_empty();
    if has_lexicon {
        m.push_str("mod lexicon;\n");
    }
    if has_joins {
        m.push_str("mod joins;\n");
    }
    let laws = t.phonology.as_ref().map(|(spec, _)| spec);
    if laws.is_some() {
        m.push_str("mod phonology;\n");
    }
    let sources: Vec<String> = t.sources.iter().map(u8::to_string).collect();
    let _ = writeln!(
        m,
        "\n/// Per cell, which model builds it when the caller gives principal parts:\n\
         /// 0 this one, `k + 1` part model `k`.\nstatic SOURCES: [u8; {}] = [{}];\n",
        t.sources.len(),
        sources.join(", ")
    );
    let _ = writeln!(m, "pub(crate) struct {ty};\n");
    let opt = |o: Option<usize>| match o {
        Some(v) => format!("Some({v})"),
        None => "None".to_string(),
    };
    let part_models: Vec<String> = t
        .part_models
        .iter()
        .map(|(c, p)| format!("({c}, {p})"))
        .collect();
    let _ = write!(
        m,
        "impl PosModel for {ty} {{\n    \
         fn cells(&self) -> usize {{\n        {}\n    }}\n    \
         fn inherent(&self) -> usize {{\n        {}\n    }}\n    \
         fn lemma_cell(&self) -> Option<usize> {{\n        {}\n    }}\n    \
         fn capitalized(&self) -> bool {{\n        {}\n    }}\n    \
         fn walk(&self) -> Walk {{\n        Walk {{\n            syllable_depth: {},\n            \
         syllable_max: {},\n            initial_depth: {},\n        }}\n    }}\n    \
         fn restore(&self) -> Option<usize> {{\n        {}\n    }}\n    \
         fn restore_front(&self) -> Option<usize> {{\n        {}\n    }}\n    \
         fn edit(&self, id: usize) -> Option<Edit<'_>> {{\n        edits::get(id).copied()\n    }}\n    \
         fn classes(&self) -> usize {{\n        {}\n    }}\n    \
         fn class(&self, class: usize) -> Option<Class<'_>> {{\n        classes::get(class).map(|c| c.class)\n    }}\n    \
         fn class_edit(&self, class: usize, cell: usize) -> Option<u32> {{\n        classes::edit(class, cell)\n    }}\n    \
         fn path<'s>(&'s self, symbols: &[char], out: &mut Path<'s>) -> bool {{\n        tree::root(symbols, out)\n    }}\n    \
         fn has_joins(&self) -> bool {{\n        {has_joins}\n    }}\n",
        t.cells,
        t.inherent,
        opt(t.lemma_cell),
        t.capitalized,
        opt(t.walk.syllable_depth),
        t.walk.syllable_max,
        opt(t.walk.initial_depth),
        opt(t.restore),
        opt(t.restore_front),
        t.classes.len(),
    );
    if has_joins {
        m.push_str(
            "    fn join(&self, prefix: &str) -> Option<Join<'_>> {\n        joins::join(prefix)\n    }\n    \
             fn join_edit(&self, class: usize, cell: usize) -> Option<u32> {\n        joins::edit(class, cell)\n    }\n",
        );
    } else {
        m.push_str(
            "    fn join(&self, _prefix: &str) -> Option<Join<'_>> {\n        None\n    }\n    \
             fn join_edit(&self, _class: usize, _cell: usize) -> Option<u32> {\n        None\n    }\n",
        );
    }
    let _ = write!(
        m,
        "    fn part_models(&self) -> &[(usize, usize)] {{\n        &[{}]\n    }}\n    \
         fn source(&self, cell: usize) -> u8 {{\n        SOURCES.get(cell).copied().unwrap_or(0)\n    }}\n",
        part_models.join(", ")
    );
    if has_lexicon {
        m.push_str("    fn lexicon(&self, key: &str) -> Option<&str> {\n        lexicon::find(key)\n    }\n");
    } else {
        m.push_str("    fn lexicon(&self, _key: &str) -> Option<&str> {\n        None\n    }\n");
    }
    if !t.lexicon_from.is_empty() {
        m.push_str("    fn lexicon_from(&self, i: usize) -> Option<(usize, &[usize])> {\n        match i {\n");
        for (i, (source, cells)) in t.lexicon_from.iter().enumerate() {
            let cells: Vec<String> = cells.iter().map(usize::to_string).collect();
            let _ = writeln!(
                m,
                "            {i} => Some(({source}, &[{}])),",
                cells.join(", ")
            );
        }
        m.push_str("            _ => None,\n        }\n    }\n");
    }
    if !lent.is_empty() {
        m.push_str("    fn cell_edits(&self, cell: usize) -> &[u32] {\n        match cell {\n");
        for &cell in lent {
            let ids: Vec<String> = t
                .cell_edits
                .get(cell)
                .map(|ids| ids.iter().map(u32::to_string).collect())
                .unwrap_or_default();
            let _ = writeln!(m, "            {cell} => &[{}],", ids.join(", "));
        }
        m.push_str("            _ => &[],\n        }\n    }\n");
    }
    if laws.is_some() {
        m.push_str("    fn phonology(&self) -> Option<&flexion::sound_law::Program> {\n        phonology::program()\n    }\n");
    }
    m.push_str("}\n");
    if laws.is_some() {
        m.push_str(
            "\n/// Whether the sound laws compile.\npub(crate) fn sound_laws_compile() -> bool {\n    phonology::program().is_some()\n}\n",
        );
    }
    files.push((format!("{dir}/mod.rs"), m));
    if let Some(spec) = laws {
        phonology(files, &format!("{dir}/phonology.rs"), spec);
    }

    // Edits.
    let edits: Vec<(Option<String>, String)> = t
        .edits
        .iter()
        .map(|e| {
            let s = &e.spec;
            let [vp, vs, va] = e.vowels;
            (
                None,
                format!(
                    "Edit::new({:?}, {:?}, {:?}, {:?}, Stress::{:?}, {}, [{}, {vp}, {vs}, {va}, {}, {}])",
                    s.front, s.prefix, s.strip, s.add, s.stress, s.mark, e.strip_chars, e.front_chars, e.front_vowels
                ),
            )
        })
        .collect();
    chunked(
        files,
        &format!("{dir}/edits"),
        "//! Every edit: `Edit::new(front, prefix, strip, add, stress, mark, [stripped\n\
         //! letters, vowels in prefix, strip and add, front letters, front vowels])`.",
        "Edit<'static>",
        "use flexion::Edit;",
        "use flexion::{Edit, Stress};",
        &edits,
    );

    classes(files, dir, t, id_ty, none);
    tree(files, &format!("{dir}/tree"), t);
    if has_lexicon {
        lexicon(files, &format!("{dir}/lexicon"), t);
    }
    if has_joins {
        joins(files, &format!("{dir}/joins.rs"), t, id_ty, none);
    }
}

/// A static table split into files of [`FILE_ITEMS`] entries, with
/// `get(i)` in the module's `mod.rs`.
/// `mod_imports` are what `mod.rs` needs to name `ty`, `imports` what
/// each chunk needs to write its entries.
#[allow(clippy::too_many_arguments)]
fn chunked(
    files: &mut Vec<(String, String)>,
    dir: &str,
    doc: &str,
    ty: &str,
    mod_imports: &str,
    imports: &str,
    items: &[(Option<String>, String)],
) {
    let chunks: Vec<&[(Option<String>, String)]> = if items.is_empty() {
        vec![&[]]
    } else {
        items.chunks(FILE_ITEMS).collect()
    };
    let mut m = String::new();
    let _ = writeln!(m, "{doc}\n");
    if !mod_imports.is_empty() {
        let _ = writeln!(m, "{mod_imports}\n");
    }
    for k in 0..chunks.len() {
        let _ = writeln!(m, "mod c{k};");
    }
    let _ = writeln!(
        m,
        "\npub(crate) fn get(i: usize) -> Option<&'static {ty}> {{\n    match i / {FILE_ITEMS} {{"
    );
    for k in 0..chunks.len() {
        let _ = writeln!(m, "        {k} => c{k}::ITEMS.get(i % {FILE_ITEMS}),");
    }
    m.push_str("        _ => None,\n    }\n}\n");
    files.push((format!("{dir}/mod.rs"), m));
    for (k, chunk) in chunks.iter().enumerate() {
        let mut c = String::new();
        if !imports.is_empty() && !chunk.is_empty() {
            let _ = writeln!(c, "{imports}\n");
        }
        if chunk.is_empty() {
            // An empty table names nothing of `imports` but its type.
            let ty_import = imports
                .lines()
                .find(|l| l.contains("ClassDef") || l.contains("Edit"));
            if let Some(l) = ty_import.filter(|l| l.contains("ClassDef")) {
                let _ = writeln!(c, "{l}\n");
            } else if ty.contains("Edit") {
                c.push_str("use flexion::Edit;\n\n");
            }
        }
        let _ = writeln!(c, "pub(crate) static ITEMS: [{ty}; {}] = [", chunk.len());
        for (comment, item) in chunk.iter() {
            if let Some(comment) = comment {
                let _ = writeln!(c, "    // {comment}");
            }
            let _ = writeln!(c, "    {item},");
        }
        c.push_str("];\n");
        files.push((format!("{dir}/c{k}.rs"), c));
    }
}

/// The classes: their records, and the per-group edit vectors they share.
fn classes(files: &mut Vec<(String, String)>, dir: &str, t: &Tables, id_ty: &str, none: &str) {
    let narrow = |e: u32| -> String {
        if e == NONE {
            none.to_string()
        } else {
            e.to_string()
        }
    };
    // Intern each group's sub-vectors, as classes share them.
    /// A group's distinct sub-vectors, and each one's index.
    type Interned = (Vec<Vec<u32>>, HashMap<Vec<u32>, usize>);
    let mut subs: Vec<Interned> = t
        .groups
        .iter()
        .map(|_| (Vec::new(), HashMap::new()))
        .collect();
    let mut class_subs: Vec<Vec<usize>> = Vec::with_capacity(t.classes.len());
    for c in 0..t.classes.len() {
        let row = t
            .class_edits
            .get(c.saturating_mul(t.cells)..c.saturating_add(1).saturating_mul(t.cells))
            .unwrap_or(&[]);
        let mut ids = Vec::with_capacity(t.groups.len());
        let mut offset = 0usize;
        for (g, &len) in t.groups.iter().enumerate() {
            let sub: Vec<u32> = row
                .get(offset..offset.saturating_add(len))
                .unwrap_or(&[])
                .to_vec();
            offset = offset.saturating_add(len);
            let Some((list, seen)) = subs.get_mut(g) else {
                continue;
            };
            let id = *seen.entry(sub.clone()).or_insert_with(|| {
                list.push(sub);
                list.len().saturating_sub(1)
            });
            ids.push(id);
        }
        class_subs.push(ids);
    }
    let n_groups = t.groups.len();
    let mut m = String::new();
    let _ = writeln!(
        m,
        "//! The classes: per class its record and, per group of cells, which of\n\
         //! the group's shared edit vectors it has (`{none}`: no form in that cell).\n"
    );
    m.push_str(if none == "u32::MAX" {
        "use flexion::Class;\n\n"
    } else {
        "use flexion::{Class, NONE};\n\n"
    });
    for g in 0..n_groups {
        let _ = writeln!(m, "mod g{g};");
    }
    m.push_str("mod list;\n\npub(crate) use list::get;\n\n");
    let _ = writeln!(
        m,
        "pub(crate) struct ClassDef {{\n    pub(crate) class: Class<'static>,\n    \
         /// One shared edit vector per group of cells.\n    pub(crate) subs: [u32; {n_groups}],\n}}\n"
    );
    let mut cell_group = Vec::with_capacity(t.cells);
    for (g, &len) in t.groups.iter().enumerate() {
        for off in 0..len {
            cell_group.push(format!("({g}, {off})"));
        }
    }
    let _ = writeln!(
        m,
        "/// Each cell's group and its place in the group.\nstatic CELL_GROUP: [(usize, usize); {}] = [{}];\n",
        cell_group.len(),
        cell_group.join(", ")
    );
    let _ = writeln!(
        m,
        "/// Class `class`'s edit for `cell` (`NONE`: no form).\n\
         pub(crate) fn edit(class: usize, cell: usize) -> Option<u32> {{\n    \
         let c = get(class)?;\n    let &(g, off) = CELL_GROUP.get(cell)?;\n    \
         let sub = usize::try_from(*c.subs.get(g)?).ok()?;\n    let e = *match g {{"
    );
    for g in 0..n_groups {
        let _ = writeln!(m, "        {g} => g{g}::get(sub)?.get(off)?,");
    }
    let _ = writeln!(
        m,
        "        _ => return None,\n    }};\n    {}\n}}",
        widen(none)
    );
    files.push((format!("{dir}/classes/mod.rs"), m));
    for (g, (list, _)) in subs.iter().enumerate() {
        let len = t.groups.get(g).copied().unwrap_or(0);
        let items: Vec<(Option<String>, String)> = list
            .iter()
            .map(|sub| {
                let v: Vec<String> = sub.iter().map(|&e| narrow(e)).collect();
                (None, format!("[{}]", v.join(", ")))
            })
            .collect();
        chunked(
            files,
            &format!("{dir}/classes/g{g}"),
            &format!("//! Group {g}'s shared edit vectors, one edit per cell of the group."),
            &format!("[{id_ty}; {len}]"),
            "",
            "",
            &items,
        );
    }
    let items: Vec<(Option<String>, String)> = t
        .classes
        .iter()
        .zip(&class_subs)
        .enumerate()
        .map(|(i, (c, ids))| {
            let values: Vec<String> = c.values.iter().map(u8::to_string).collect();
            let ids: Vec<String> = ids.iter().map(usize::to_string).collect();
            (
                Some(format!("{i}: {}", example(t, i, &c.example))),
                format!(
                    "ClassDef {{ class: Class {{ strip: {:?}, front: {:?}, lemma: (Stress::{:?}, {}), values: &[{}] }}, subs: [{}] }}",
                    c.strip,
                    c.front,
                    c.lemma.0,
                    c.lemma.1,
                    values.join(", "),
                    ids.join(", ")
                ),
            )
        })
        .collect();
    chunked(
        files,
        &format!("{dir}/classes/list"),
        "//! Every class, with a word of it and its first forms.",
        "ClassDef",
        "use super::ClassDef;",
        "use super::super::ClassDef;\nuse flexion::{Class, Stress};",
        &items,
    );
}

/// "like книга: книги, книге, книгу": a class's example word and the forms
/// its first edits give it.
fn example(t: &Tables, class: usize, word: &str) -> String {
    if word.is_empty() {
        return "a class".to_string();
    }
    let forms: Vec<String> = (0..t.cells)
        .filter(|&cell| Some(cell) != t.lemma_cell)
        .filter_map(|cell| {
            let e = t
                .class_edits
                .get(class.checked_mul(t.cells)?.checked_add(cell)?)?;
            let e = &t.edits.get(usize::try_from(*e).ok()?)?.spec;
            let stem = word
                .strip_prefix(e.front.as_str())?
                .strip_suffix(e.strip.as_str())?;
            Some(format!("{}{stem}{}", e.prefix, e.add))
        })
        .take(3)
        .collect();
    if forms.is_empty() {
        format!("like {word}")
    } else {
        format!("like {word}: {}, …", forms.join(", "))
    }
}

/// The tree as functions of `match`es over the symbols left to read.
fn tree(files: &mut Vec<(String, String)>, dir: &str, t: &Tables) {
    let n = t.nodes.len();
    // Subtree sizes: children come after their parent (breadth-first).
    let mut size = vec![1usize; n];
    for i in (0..n).rev() {
        let Some(node) = t.nodes.get(i) else {
            continue;
        };
        let kids: usize = (node.first_child..node.first_child.saturating_add(node.children))
            .filter_map(|c| size.get(c).copied())
            .sum();
        if let Some(s) = size.get_mut(i) {
            *s = s.saturating_add(kids);
        }
    }
    // Plan, then write: which nodes start a function (each inlines whole
    // child subtrees while they fit its budget) and which file each is in.
    // The nodes with a distribution, numbered densely.
    let mut defs: Vec<Option<usize>> = vec![None; n];
    let mut next_def = 0usize;
    for (i, node) in t.nodes.iter().enumerate() {
        if node.kind != NodeKind::Bare
            && let Some(slot) = defs.get_mut(i)
        {
            *slot = Some(next_def);
            next_def = next_def.saturating_add(1);
        }
    }
    let (order, _) = tree_pass(t, &size, None, &defs);
    let mut file_of: HashMap<usize, usize> = HashMap::new();
    let (mut file, mut in_file) = (0usize, 0usize);
    for &(node, nodes) in &order {
        if in_file > 0 && in_file.saturating_add(nodes) > FILE_NODES {
            file = file.saturating_add(1);
            in_file = 0;
        }
        in_file = in_file.saturating_add(nodes);
        file_of.insert(node, file);
    }
    let (_, bodies) = tree_pass(t, &size, Some(&file_of), &defs);
    let files_n = file.saturating_add(1);
    let mut by_file: Vec<String> = vec![String::new(); files_n];
    for ((node, _), body) in order.iter().zip(bodies) {
        let k = file_of.get(node).copied().unwrap_or(0);
        if let Some(text) = by_file.get_mut(k) {
            text.push_str(&body);
            text.push('\n');
        }
    }
    let mut m = String::new();
    m.push_str(
        "//! The suffix tree: a word's symbols (its letters from the last one back,\n\
         //! the walk's tokens, then the start of the word) choose the arms; each node\n\
         //! on the way adds its distribution over classes. A node stores the classes\n\
         //! of the words under it, counted; its distribution is computed from them on\n\
         //! first use, smoothed toward its nearest ancestor's. The walk returns\n\
         //! whether it reached the word's own node.\n\n\
         use flexion::Path;\nuse flexion::tables::{NodeKind, Smoothed, smooth_node};\nuse std::sync::OnceLock;\n\n\
         mod nodes;\n",
    );
    for k in 0..files_n {
        let _ = writeln!(m, "mod t{k};");
    }
    let narrow = t.classes.len() <= usize::from(u16::MAX).saturating_add(1);
    // The constructors the nodes use.
    let has = |k: NodeKind| t.nodes.iter().any(|n| n.kind == k);
    let mut ctors = String::new();
    if has(NodeKind::Root) {
        ctors.push_str(
            "    pub(crate) const fn root(counts: &'static [(u32, f32)]) -> Node {\n        \
             Node { kind: NodeKind::Root, parent: u32::MAX, counts }\n    }\n",
        );
    }
    if has(NodeKind::Word) {
        ctors.push_str(
            "    pub(crate) const fn word(counts: &'static [(u32, f32)]) -> Node {\n        \
             Node { kind: NodeKind::Word, parent: u32::MAX, counts }\n    }\n",
        );
    }
    if has(NodeKind::Inner) {
        ctors.push_str(
            "    pub(crate) const fn inner(parent: u32, counts: &'static [(u32, f32)]) -> Node {\n        \
             Node { kind: NodeKind::Inner, parent, counts }\n    }\n",
        );
    }
    let _ = write!(
        m,
        "\npub(crate) use t0::n0 as root;\n\n\
         /// Smoothing strength, the tail cut, and whether probabilities are rounded to\n\
         /// 1/65535 (see `flexion::tables::smooth_node`).\n\
         const ALPHA: f64 = {:?};\nconst EPSILON: f64 = {:?};\nconst NARROW: bool = {narrow};\n\n\
         /// A node with a distribution: how it comes from its counts, the node it is\n\
         /// smoothed toward (`u32::MAX`: none), and its counts `(class, weight)`.\n\
         pub(crate) struct Node {{\n    kind: NodeKind,\n    parent: u32,\n    \
         counts: &'static [(u32, f32)],\n}}\n\n\
         impl Node {{\n{ctors}}}\n\n\
         /// Each node's distribution, computed on first use.\n\
         static CACHE: [OnceLock<Smoothed>; {next_def}] = [const {{ OnceLock::new() }}; {next_def}];\n\n\
         fn dist(i: usize) -> Option<&'static Smoothed> {{\n    \
         let node = nodes::get(i)?;\n    \
         Some(CACHE.get(i)?.get_or_init(|| {{\n        \
         let parent = (node.parent != u32::MAX)\n            .then(|| usize::try_from(node.parent).ok())\n            .flatten()\n            .and_then(dist);\n        \
         let q = parent.map_or(&[][..], |p| p.entries.as_slice());\n        \
         smooth_node(node.kind, node.counts, q, ALPHA, EPSILON, NARROW)\n    }}))\n}}\n\n\
         /// Add node `i`'s distribution to the path.\n\
         pub(crate) fn push(out: &mut Path<'_>, i: usize) {{\n    \
         if let Some(d) = dist(i).filter(|d| !d.entries.is_empty()) {{\n        \
         out.push(&d.entries, d.mass);\n    }}\n}}\n",
        t.alpha, t.epsilon
    );
    files.push((format!("{dir}/mod.rs"), m));
    let table: Vec<(Option<String>, String)> = t
        .nodes
        .iter()
        .filter(|n| n.kind != NodeKind::Bare)
        .map(|n| {
            let counts: Vec<String> = n
                .counts
                .iter()
                .map(|&(c, w)| format!("({c}, {})", f(w)))
                .collect();
            let counts = counts.join(", ");
            let parent = n.parent.and_then(|p| defs.get(p).copied().flatten());
            let code = match (n.kind, parent) {
                (NodeKind::Root, _) => format!("Node::root(&[{counts}])"),
                (NodeKind::Word, _) => format!("Node::word(&[{counts}])"),
                (_, Some(p)) => format!("Node::inner({p}, &[{counts}])"),
                (_, None) => format!("Node::inner(u32::MAX, &[{counts}])"),
            };
            (None, code)
        })
        .collect();
    chunked(
        files,
        &format!("{dir}/nodes"),
        "//! Every tree node with a distribution, in the order the tree functions\n\
         //! number them.",
        "Node",
        "use super::Node;",
        "use super::super::Node;",
        &table,
    );
    for (k, text) in by_file.into_iter().enumerate() {
        files.push((
            format!("{dir}/t{k}.rs"),
            format!("use flexion::Path;\n\n{text}"),
        ));
    }
}

/// Every tree function, in the order written: `(its node, the nodes it
/// holds)`, and (when `file_of` is known) its code.
fn tree_pass(
    t: &Tables,
    size: &[usize],
    file_of: Option<&HashMap<usize, usize>>,
    defs: &[Option<usize>],
) -> (Vec<(usize, usize)>, Vec<String>) {
    let mut roots: Vec<(usize, Vec<char>)> = vec![(0, Vec::new())];
    let mut order = Vec::new();
    let mut bodies = Vec::new();
    let mut next = 0usize;
    while let Some((node, path)) = roots.get(next).cloned() {
        next = next.saturating_add(1);
        let mut code = String::new();
        let mut budget = FN_NODES.saturating_sub(1);
        let mut deferred = Vec::new();
        node_code(
            &mut code,
            &Ctx {
                t,
                size,
                file_of,
                defs,
            },
            node,
            node == 0,
            1,
            &path,
            &mut budget,
            &mut deferred,
        );
        // A function whose nodes hold no distribution and call nothing
        // leaves `out` alone.
        let out = if code.contains("out") { "out" } else { "_out" };
        let mut body = String::new();
        let _ = writeln!(body, "/// {}.", describe(&path));
        let _ = writeln!(
            body,
            "pub(crate) fn n{node}(s: &[char], {out}: &mut Path<'_>) -> bool {{"
        );
        body.push_str(&code);
        body.push_str("}\n");
        order.push((node, FN_NODES.saturating_sub(budget)));
        if file_of.is_some() {
            bodies.push(body);
        }
        roots.extend(deferred);
    }
    (order, bodies)
}

struct Ctx<'a> {
    t: &'a Tables,
    size: &'a [usize],
    file_of: Option<&'a HashMap<usize, usize>>,
    /// Per node, its place in the node table (nodes without a distribution
    /// have none).
    defs: &'a [Option<usize>],
}

/// Code for `node`: its distribution, then a `match` on the next symbol.
#[allow(clippy::too_many_arguments)]
fn node_code(
    out: &mut String,
    cx: &Ctx,
    index: usize,
    is_root: bool,
    depth: usize,
    path: &[char],
    budget: &mut usize,
    deferred: &mut Vec<(usize, Vec<char>)>,
) {
    let t = cx.t;
    // One tab per level: the tree nests deep, and four spaces a level were
    // most of its bytes.
    let pad = "\t".repeat(depth);
    let Some(node) = t.nodes.get(index) else {
        let _ = writeln!(out, "{pad}false");
        return;
    };
    if let Some(d) = cx.defs.get(index).copied().flatten() {
        let _ = writeln!(out, "{pad}super::push(out, {d});");
    }
    let kids: &[NodeRec] = t.children(node);
    if kids.is_empty() {
        if is_root {
            let _ = writeln!(out, "{pad}let _ = s;\n{pad}false");
        } else {
            let _ = writeln!(out, "{pad}s.is_empty()");
        }
        return;
    }
    let _ = writeln!(out, "{pad}match s {{");
    if !is_root {
        let _ = writeln!(out, "{pad}\t[] => true,");
    }
    for (i, kid) in kids.iter().enumerate() {
        let child = node.first_child.saturating_add(i);
        let letters: Vec<String> = kid.label.chars().map(|c| format!("{c:?}")).collect();
        let pattern = format!("[{}, s @ ..]", letters.join(", "));
        let mut kid_path = path.to_vec();
        kid_path.extend(kid.label.chars());
        let kid_size = cx.size.get(child).copied().unwrap_or(1);
        if kid_size <= *budget && depth / 2 < MAX_NESTING {
            *budget = budget.saturating_sub(kid_size);
            let _ = writeln!(out, "{pad}\t{pattern} => {{");
            node_code(
                out,
                cx,
                child,
                false,
                depth.saturating_add(2),
                &kid_path,
                budget,
                deferred,
            );
            let _ = writeln!(out, "{pad}\t}}");
        } else {
            let file = cx.file_of.and_then(|m| m.get(&child)).copied().unwrap_or(0);
            let _ = writeln!(out, "{pad}\t{pattern} => super::t{file}::n{child}(s, out),");
            deferred.push((child, kid_path));
        }
    }
    let _ = writeln!(out, "{pad}\t_ => false,\n{pad}}}");
}

/// What a tree path means, for a function's doc comment: "Words ending
/// -ка", "The word кот", with the walk's tokens.
fn describe(path: &[char]) -> String {
    if path.is_empty() {
        return "Every word".to_string();
    }
    let mut letters: Vec<char> = Vec::new();
    let mut notes: Vec<String> = Vec::new();
    let mut whole = false;
    for &c in path {
        let u = u32::from(c);
        if c == BOUNDARY {
            whole = true;
        } else if u >= INITIAL_TOKEN {
            if let Some(l) = char::from_u32(u.saturating_sub(INITIAL_TOKEN)) {
                notes.push(format!("starting with {l}"));
            }
        } else if (SYLLABLE_TOKEN..SYLLABLE_TOKEN.saturating_add(16)).contains(&u) {
            notes.push(format!("{} syllables", u.saturating_sub(SYLLABLE_TOKEN)));
        } else {
            letters.push(c);
        }
    }
    let word: String = letters.iter().rev().collect();
    let head = if whole {
        format!("The word {word}")
    } else {
        format!("Words ending -{word}")
    };
    if notes.is_empty() {
        head
    } else {
        format!("{head} ({})", notes.join(", "))
    }
}

/// The lexicon as `match`es on the lookup key.
fn lexicon(files: &mut Vec<(String, String)>, dir: &str, t: &Tables) {
    let chunks: Vec<&[(String, String)]> = t.lexicon.chunks(FILE_ITEMS).collect();
    let mut m = String::new();
    m.push_str(
        "//! Lemmas written in full that another part of speech attests, by lookup\n\
         //! key (the lemma folded as callers may type it).\n\n",
    );
    for k in 0..chunks.len() {
        let _ = writeln!(m, "mod c{k};");
    }
    m.push_str("\npub(crate) fn find(key: &str) -> Option<&'static str> {\n    ");
    let calls: Vec<String> = (0..chunks.len())
        .map(|k| format!("c{k}::find(key)"))
        .collect();
    let _ = writeln!(
        m,
        "{}",
        calls
            .iter()
            .enumerate()
            .map(|(i, c)| if i == 0 {
                c.clone()
            } else {
                format!(".or_else(|| {c})")
            })
            .collect::<String>()
    );
    m.push_str("}\n");
    files.push((format!("{dir}/mod.rs"), m));
    for (k, chunk) in chunks.iter().enumerate() {
        // Keys are sorted: each `match` holds a run of them, and the first
        // key of the next run says where to look.
        let runs: Vec<&[(String, String)]> = chunk.chunks(MATCH_ARMS).collect();
        let mut c = String::new();
        c.push_str("pub(crate) fn find(key: &str) -> Option<&'static str> {\n");
        for (r, run) in runs.iter().enumerate().skip(1).rev() {
            if let Some((first, _)) = run.first() {
                let _ = writeln!(
                    c,
                    "    if key >= {first:?} {{\n        return m{r}(key);\n    }}"
                );
            }
        }
        c.push_str("    m0(key)\n}\n");
        for (r, run) in runs.iter().enumerate() {
            let _ = writeln!(
                c,
                "\nfn m{r}(key: &str) -> Option<&'static str> {{\n    Some(match key {{"
            );
            for (key, written) in run.iter() {
                let _ = writeln!(c, "        {key:?} => {written:?},");
            }
            c.push_str("        _ => return None,\n    })\n}\n");
        }
        files.push((format!("{dir}/c{k}.rs"), c));
    }
}

/// The code that turns a stored edit index `e` into the engine's: 16-bit
/// indices mark "no form" with their own maximum, 32-bit ones are as is.
fn widen(none: &str) -> String {
    if none == "u32::MAX" {
        "Some(e)".to_string()
    } else {
        format!("Some(if e == {none} {{ NONE }} else {{ u32::from(e) }})")
    }
}

/// The sound laws, in `sound-law`'s notation, compiled once on first use.
fn phonology(files: &mut Vec<(String, String)>, path: &str, spec: &flexion::tables::PhonologySpec) {
    let mut m = String::new();
    m.push_str(
        "//! The sound laws: edits carry trigger characters that set them off;\n\
         //! the last rule deletes any trigger left.\n\n\
         use flexion::sound_law::{Program, RuleSet, sound_laws};\nuse std::sync::OnceLock;\n\n\
         const LAWS: RuleSet<'static> = sound_laws! {\n    classes {\n",
    );
    for (name, members) in &spec.classes {
        let members: Vec<String> = members.iter().map(|x| format!("{x:?}")).collect();
        let _ = writeln!(m, "        {name} = [{}];", members.join(", "));
    }
    m.push_str("    }\n");
    if !spec.maps.is_empty() {
        m.push_str("    maps {\n");
        for (name, entries) in &spec.maps {
            let entries: Vec<String> = entries
                .iter()
                .map(|(a, b)| format!("{a:?} => {b:?}"))
                .collect();
            let _ = writeln!(m, "        {name} = [{}];", entries.join(", "));
        }
        m.push_str("    }\n");
    }
    m.push_str("    rules {\n");
    for r in &spec.rules {
        let context = if r.left.is_empty() && r.right.is_empty() {
            String::new()
        } else {
            format!(" / {:?} _ {:?}", r.left, r.right)
        };
        let _ = writeln!(
            m,
            "        {}: {:?} => {:?}{context};",
            r.name, r.target, r.replacement
        );
    }
    m.push_str(
        "    }\n};\n\n\
         pub(crate) fn program() -> Option<&'static Program> {\n    \
         static PROGRAM: OnceLock<Option<Program>> = OnceLock::new();\n    \
         PROGRAM.get_or_init(|| LAWS.compile().ok()).as_ref()\n}\n",
    );
    files.push((path.to_string(), m));
}

/// The join model: a `match` on the prefix, and the join classes' edits.
fn joins(files: &mut Vec<(String, String)>, path: &str, t: &Tables, id_ty: &str, none: &str) {
    let mut m = String::new();
    m.push_str(
        "//! The join model: prefixes that, put before an attested word, make a word\n\
         //! that inflects through it.\n\n",
    );
    m.push_str(if none == "u32::MAX" {
        "use flexion::Join;\n\n"
    } else {
        "use flexion::{Join, NONE};\n\n"
    });
    m.push_str(
        "pub(crate) fn join(prefix: &str) -> Option<Join<'static>> {\n    Some(match prefix {\n",
    );
    let mut joins = t.joins.iter().peekable();
    while let Some(j) = joins.next() {
        // Of equal prefixes the last is the one read.
        if joins.peek().is_some_and(|n| n.prefix == j.prefix) {
            continue;
        }
        let classes: Vec<String> = j
            .classes
            .iter()
            .map(|&(c, p)| format!("({c}, {})", f(p)))
            .collect();
        let inherent: Vec<String> = j
            .inherent
            .iter()
            .map(|&(a, b, c, p)| format!("({a}, {b}, {c}, {})", f(p)))
            .collect();
        let _ = writeln!(
            m,
            "        {:?} => Join {{ split: {}, classes: &[{}], inherent: &[{}] }},",
            j.prefix,
            f(j.split),
            classes.join(", "),
            inherent.join(", ")
        );
    }
    m.push_str("        _ => return None,\n    })\n}\n\n");
    let rows: Vec<String> = t
        .join_classes
        .chunks(t.cells.max(1))
        .map(|row| {
            let v: Vec<String> = row
                .iter()
                .map(|&e| {
                    if e == NONE {
                        none.to_string()
                    } else {
                        e.to_string()
                    }
                })
                .collect();
            format!("    [{}],", v.join(", "))
        })
        .collect();
    let _ = writeln!(
        m,
        "/// Per join class, one edit per cell (`{none}`: no form).\nstatic CLASSES: [[{id_ty}; {}]; {}] = [\n{}\n];\n",
        t.cells,
        rows.len(),
        rows.join("\n")
    );
    let _ = writeln!(
        m,
        "pub(crate) fn edit(class: usize, cell: usize) -> Option<u32> {{\n    \
         let e = *CLASSES.get(class)?.get(cell)?;\n    {}\n}}",
        widen(none)
    );
    files.push((path.to_string(), m));
}
