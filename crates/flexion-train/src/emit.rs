//! Writing the generated crate: `Cargo.toml`, `src/lib.rs` (feature enums,
//! typed functions, a settings value), `src/model.bin`, the config's
//! hand-written `src/extra.rs`, a README with the evaluation report, and the
//! data license.

use crate::cells::{Cells, GroupCells};
use crate::spec::{Feature, Language};
use std::fmt::Write as _;
use std::path::Path;

/// Write the crate for `lang` into `dir` (created if missing).
pub fn emit(lang: &Language, blob: &[u8], report: &str, dir: &Path) -> Result<(), String> {
    let src = dir.join("src");
    std::fs::create_dir_all(&src).map_err(|e| format!("{}: {e}", src.display()))?;
    let write = |path: &Path, data: &[u8]| {
        std::fs::write(path, data).map_err(|e| format!("{}: {e}", path.display()))
    };
    write(&dir.join("Cargo.toml"), manifest(lang).as_bytes())?;
    write(&src.join("model.bin"), blob)?;
    write(&src.join("lib.rs"), library(lang)?.as_bytes())?;
    if let Some(extra) = lang.extra {
        write(&src.join("extra.rs"), extra.as_bytes())?;
    }
    write(&dir.join("README.md"), readme(lang, report).as_bytes())?;
    write(&dir.join("DATA-LICENSE.md"), data_license(lang).as_bytes())?;
    Ok(())
}

fn manifest(lang: &Language) -> String {
    format!(
        r#"# Generated by flexion-train from configs/src/{module}.rs. Regenerate with
# `cargo xtask build {name} --dump <kaikki {display} dump>`; don't edit by hand.

[package]
name = "{name}"
version = "{version}"
description = "{description}"
readme = "README.md"
license = "(MIT OR Apache-2.0) AND CC-BY-SA-4.0"
keywords = ["{name}", "inflection", "morphology", "linguistics", "nlp"]
categories = ["text-processing"]
include = ["src/**", "README.md", "DATA-LICENSE.md", "LICENSE-MIT", "LICENSE-APACHE"]
authors.workspace = true
edition.workspace = true
repository.workspace = true
rust-version.workspace = true

[dependencies]
flexion = {{ workspace = true }}

[lints]
workspace = true
"#,
        name = lang.name,
        module = lang.name.replace('-', "_"),
        display = lang.display,
        version = lang.version,
        description = lang.description,
    )
}

fn snake(name: &str) -> String {
    let mut out = String::new();
    for (i, c) in name.chars().enumerate() {
        if c.is_uppercase() {
            if i > 0 {
                out.push('_');
            }
            out.extend(c.to_lowercase());
        } else {
            out.push(c);
        }
    }
    out
}

/// The settings type's name: the crate name in camel case (`AncientGreek`).
fn settings_name(lang: &Language) -> String {
    lang.name
        .split(['-', '_'])
        .map(|part| {
            let mut c = part.chars();
            c.next()
                .map(|f| f.to_uppercase().chain(c).collect::<String>())
                .unwrap_or_default()
        })
        .collect()
}

fn library(lang: &Language) -> Result<String, String> {
    let mut s = String::new();
    let settings = settings_name(lang);
    let stress = !lang.spelling.stress_marks.is_empty();
    let _ = writeln!(
        s,
        "// Generated by flexion-train from configs/src/{}.rs; don't edit by hand.\n\n#![doc = include_str!(\"../README.md\")]\n#![forbid(unsafe_code)]\n",
        lang.name.replace('-', "_")
    );
    s.push_str(
        "pub use flexion::Candidate;\nuse flexion::{Model, Options};\nuse std::sync::OnceLock;\n\n",
    );
    if lang.extra.is_some() {
        s.push_str("mod extra;\npub use extra::*;\n\n");
    }
    s.push_str(
        "static BLOB: &[u8] = include_bytes!(\"model.bin\");\n\n\
         fn model() -> Option<&'static Model<'static>> {\n    \
         static MODEL: OnceLock<Option<Model<'static>>> = OnceLock::new();\n    \
         MODEL.get_or_init(|| Model::from_bytes(BLOB)).as_ref()\n}\n\n",
    );

    // Feature enums, for every feature some part of speech uses.
    for f in &lang.features {
        let used = lang.parts.iter().any(|p| {
            p.inherent.contains(&f.name) || p.groups.iter().any(|g| g.features.contains(&f.name))
        });
        if used {
            feature_enum(&mut s, f);
        }
    }

    // Settings.
    let _ = writeln!(
        s,
        "/// Output settings. The free functions use [`{settings}::default()`].\n\
         #[derive(Debug, Clone, Copy, PartialEq, Eq)]\n\
         pub struct {settings} {{\n    stress: bool,\n    marks: bool,\n}}\n\n\
         impl Default for {settings} {{\n    fn default() -> Self {{\n        Self::new()\n    }}\n}}\n"
    );
    let _ = writeln!(
        s,
        "impl {settings} {{\n    pub const fn new() -> Self {{\n        {settings} {{\n            stress: true,\n            marks: true,\n        }}\n    }}\n"
    );
    let setting = lang.spelling.stress_setting;
    if !setting.is_empty() {
        let _ = writeln!(
            s,
            "    /// Write {setting} (on by default).\n    pub const fn {setting}(mut self, on: bool) -> Self {{\n        self.stress = on;\n        self\n    }}\n"
        );
    }
    let setting = lang.spelling.marks_setting;
    if !setting.is_empty() {
        let _ = writeln!(
            s,
            "    /// Write {setting} (on by default); off writes the plain letters.\n    pub const fn {setting}(mut self, on: bool) -> Self {{\n        self.marks = on;\n        self\n    }}\n"
        );
    }
    s.push_str(
        "    fn options(&self) -> Options {\n        Options {\n            stress: self.stress,\n            marks: self.marks,\n        }\n    }\n",
    );
    let mut free = String::new();
    for (pi, part) in lang.parts.iter().enumerate() {
        let cells = Cells::new(lang, part)?;
        let citation_doc = citation_doc(lang, part, &cells);
        for g in &cells.groups {
            methods(&mut s, &mut free, pi, g, &citation_doc, &settings);
        }
    }
    s.push_str("}\n\n");
    s.push_str(&free);

    // Inherent features.
    for (pi, part) in lang.parts.iter().enumerate() {
        for (fi, name) in part.inherent.iter().enumerate() {
            let Some(f) = lang.feature(name) else {
                continue;
            };
            let unique = lang
                .parts
                .iter()
                .filter(|p| p.inherent.contains(name))
                .count()
                == 1;
            let func = if unique {
                snake(name)
            } else {
                format!("{}_{}", part.name, snake(name))
            };
            let _ = writeln!(
                s,
                "/// The {feat} of a {pos} lemma (or citation), with confidence, most likely\n\
                 /// first. Predicted from the word's shape when it isn't attested.\n\
                 pub fn {func}(word: &str) -> Vec<({ty}, f32)> {{\n    \
                 inherent({pi}, {fi}, word, &{ty}::ALL)\n}}\n",
                feat = snake(name).replace('_', " "),
                pos = part.name,
                ty = f.name,
            );
        }
    }
    if stress {
        s.push_str(
            "/// `s` without stress marks.\npub fn without_stress(s: &str) -> String {\n    model().map_or_else(|| s.to_string(), |m| m.spelling().unstressed(s))\n}\n\n",
        );
    }
    s.push_str(
        "/// Per part of speech: the cells a citation's extra parts fill, and the\n\
         /// markers of its inherent features (`m`, `anim`, …).\n\
         struct Part {\n    citation: &'static [usize],\n    markers: &'static [&'static [&'static str]],\n}\n\n",
    );
    let _ = writeln!(s, "const PARTS: [Part; {}] = [", lang.parts.len());
    for part in &lang.parts {
        let cells = Cells::new(lang, part)?;
        let citation: Vec<String> = part
            .citation
            .iter()
            .filter_map(|(g, v)| cells.find(g, v))
            .map(|c| c.to_string())
            .collect();
        let markers: Vec<String> = lang
            .markers(part)
            .iter()
            .map(|names| {
                format!(
                    "&[{}]",
                    names
                        .iter()
                        .map(|n| format!("{n:?}"))
                        .collect::<Vec<_>>()
                        .join(", ")
                )
            })
            .collect();
        let _ = writeln!(
            s,
            "    Part {{ citation: &[{}], markers: &[{}] }}, // {}",
            citation.join(", "),
            markers.join(", "),
            part.name
        );
    }
    s.push_str(
        "];\n\n\
         fn citation<'s>(p: &flexion::Pos<'_, 'static>, pos: usize, word: &'s str) -> flexion::Citation<'s> {\n    \
         match PARTS.get(pos) {\n        \
         Some(part) => p.citation_marked(word, part.citation, part.markers),\n        \
         None => p.citation(word, &[]),\n    }\n}\n",
    );
    let optional = lang
        .parts
        .iter()
        .any(|p| p.groups.iter().any(|g| g.optional));
    let required = lang
        .parts
        .iter()
        .any(|p| p.groups.iter().any(|g| !g.optional));
    let inherent = lang.parts.iter().any(|p| !p.inherent.is_empty());
    for (helper, used) in [
        (QUICK, required),
        (OPTIONAL, optional),
        (INHERENT, inherent),
    ] {
        if used {
            s.push_str(helper);
        }
    }
    Ok(s)
}

fn feature_enum(s: &mut String, f: &Feature) {
    let _ = writeln!(
        s,
        "/// {}\n#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord)]\npub enum {} {{",
        f.doc, f.name
    );
    for v in &f.values {
        let _ = writeln!(s, "    {},", v.name);
    }
    s.push_str("}\n\n");
    let _ = writeln!(
        s,
        "impl {} {{\n    /// Every value, in order.\n    pub const ALL: [{}; {}] = [",
        f.name,
        f.name,
        f.values.len()
    );
    for v in &f.values {
        let _ = writeln!(s, "        {}::{},", f.name, v.name);
    }
    s.push_str("    ];\n\n    /// Short name, as in cell names (`");
    s.push_str(f.values.first().map_or("", |v| v.short));
    s.push_str("`).\n    pub const fn short(self) -> &'static str {\n        match self {\n");
    for v in &f.values {
        let _ = writeln!(s, "            {}::{} => \"{}\",", f.name, v.name, v.short);
    }
    s.push_str("        }\n    }\n}\n\n");
}

fn citation_doc(lang: &Language, part: &crate::spec::PartOfSpeech, cells: &Cells) -> String {
    let markers: Vec<String> = lang
        .markers(part)
        .into_iter()
        .flatten()
        .map(|m| format!("`{m}`"))
        .collect();
    let marker_doc = if markers.is_empty() {
        String::new()
    } else {
        format!(
            "\n    /// Any part may end with markers of the word's own features ({}), as a\n    /// dictionary prints them.",
            markers.join(", ")
        )
    };
    if part.citation.is_empty() {
        return marker_doc;
    }
    let parts: Vec<String> = part
        .citation
        .iter()
        .filter_map(|(g, v)| cells.find(g, v))
        .map(|c| format!("`{}`", cells.name(c)))
        .collect();
    format!(
        "\n    ///\n    /// `word` may be a citation: the lemma, then any of {} separated by commas.\n    /// Given parts are output exactly; the rest is predicted to agree with them.{marker_doc}",
        parts.join(", ")
    )
}

fn methods(
    s: &mut String,
    free: &mut String,
    pi: usize,
    g: &GroupCells,
    citation_doc: &str,
    settings: &str,
) {
    let positional = g.features.len() <= 3;
    let args: Vec<(String, &'static str)> =
        g.features.iter().map(|f| (snake(f.name), f.name)).collect();
    // The cell index: offset + mixed radix over the features' value indices.
    let mut index = format!("{}", g.offset);
    if !args.is_empty() {
        let mut radix_expr = String::new();
        for (i, (f, (arg, _))) in g.features.iter().zip(&args).enumerate() {
            let access = if positional {
                arg.clone()
            } else {
                format!("cell.{arg}")
            };
            radix_expr = match (i, f.values.len()) {
                (0, _) => format!("{access} as usize"),
                (_, 1) => radix_expr,
                (_, n) => format!("({radix_expr}) * {n} + {access} as usize"),
            };
        }
        index = if g.offset == 0 {
            radix_expr
        } else {
            format!("{} + {radix_expr}", g.offset)
        };
    }
    let cell_ty = format!("{}Cell", pascal(g.name));
    if !positional {
        let _ = writeln!(
            free,
            "/// The cell of [`{}`].\n#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]\npub struct {cell_ty} {{",
            g.name
        );
        for (arg, ty) in &args {
            let _ = writeln!(free, "    pub {arg}: {ty},");
        }
        free.push_str("}\n\n");
    }
    let params: String = if positional {
        args.iter().map(|(a, t)| format!(", {a}: {t}")).collect()
    } else {
        format!(", cell: {cell_ty}")
    };
    let call_args: String = if positional {
        args.iter().map(|(a, _)| format!(", {a}")).collect()
    } else {
        ", cell".to_string()
    };
    let doc = g.group.doc;
    let name = g.name;
    if g.group.optional {
        let _ = writeln!(
            s,
            "\n    /// {doc}{citation_doc}\n    pub fn {name}(&self, word: &str{params}) -> Option<String> {{\n        optional({pi}, word, {index}, self.options())\n    }}\n\n    \
             /// Every candidate for [`{settings}::{name}`], most likely first. Confidences sum\n    \
             /// to the probability that the word has such a form at all.\n    \
             pub fn {name}_scored(&self, word: &str{params}) -> Vec<Candidate> {{\n        optional_scored({pi}, word, {index}, self.options())\n    }}"
        );
        let _ = writeln!(
            free,
            "/// {doc}{}\npub fn {name}(word: &str{params}) -> Option<String> {{\n    {settings}::new().{name}(word{call_args})\n}}\n\n\
             /// Every candidate for [`{name}`], most likely first. Confidences sum to the\n/// probability that the word has such a form at all.\npub fn {name}_scored(word: &str{params}) -> Vec<Candidate> {{\n    {settings}::new().{name}_scored(word{call_args})\n}}\n",
            citation_doc.replace("\n    ///", "\n///")
        );
    } else {
        let _ = writeln!(
            s,
            "\n    /// {doc}{citation_doc}\n    pub fn {name}(&self, word: &str{params}) -> String {{\n        quick({pi}, word, {index}, self.options())\n    }}\n\n    \
             /// Every candidate for [`{settings}::{name}`], most likely first; confidences sum to 1.\n    \
             pub fn {name}_scored(&self, word: &str{params}) -> Vec<Candidate> {{\n        scored({pi}, word, {index}, self.options())\n    }}"
        );
        let _ = writeln!(
            free,
            "/// {doc}{}\npub fn {name}(word: &str{params}) -> String {{\n    {settings}::new().{name}(word{call_args})\n}}\n\n\
             /// Every candidate for [`{name}`], most likely first; confidences sum to 1.\npub fn {name}_scored(word: &str{params}) -> Vec<Candidate> {{\n    {settings}::new().{name}_scored(word{call_args})\n}}\n",
            citation_doc.replace("\n    ///", "\n///")
        );
    }
}

fn pascal(name: &str) -> String {
    name.split('_')
        .map(|w| {
            let mut c = w.chars();
            c.next()
                .map(|f| f.to_uppercase().chain(c).collect::<String>())
                .unwrap_or_default()
        })
        .collect()
}

const QUICK: &str = r#"
fn quick(pos: usize, word: &str, cell: usize, options: Options) -> String {
    match model().and_then(|m| m.pos(pos)) {
        Some(p) => p.best(&citation(&p, pos, word), cell, options),
        None => word.to_string(),
    }
}

fn scored(pos: usize, word: &str, cell: usize, options: Options) -> Vec<Candidate> {
    match model().and_then(|m| m.pos(pos)) {
        Some(p) => p.candidates(&citation(&p, pos, word), cell, options),
        None => vec![Candidate { form: word.to_string(), confidence: 0.0 }],
    }
}

"#;

const OPTIONAL: &str = r#"
fn optional(pos: usize, word: &str, cell: usize, options: Options) -> Option<String> {
    let p = model()?.pos(pos)?;
    let c = citation(&p, pos, word);
    (p.has_cell(&c, cell) >= 0.5).then(|| p.best(&c, cell, options))
}

fn optional_scored(pos: usize, word: &str, cell: usize, options: Options) -> Vec<Candidate> {
    let Some(p) = model().and_then(|m| m.pos(pos)) else {
        return Vec::new();
    };
    let c = citation(&p, pos, word);
    let exists = p.has_cell(&c, cell);
    let mut out = p.candidates(&c, cell, options);
    for x in &mut out {
        x.confidence *= exists;
    }
    out
}

"#;

const INHERENT: &str = r#"
fn inherent<T: Copy>(pos: usize, feature: usize, word: &str, values: &[T]) -> Vec<(T, f32)> {
    let Some(p) = model().and_then(|m| m.pos(pos)) else {
        return Vec::new();
    };
    let c = citation(&p, pos, word);
    p.inherent(&c, feature)
        .into_iter()
        .filter_map(|(v, q)| values.get(usize::from(v)).map(|&t| (t, q)))
        .collect()
}
"#;

fn readme(lang: &Language, report: &str) -> String {
    let sources = lang
        .editions
        .iter()
        .map(|e| format!(" and of {}'s", e.name))
        .collect::<String>();
    let links = lang
        .editions
        .iter()
        .map(|e| format!(" and [{}](https://{}.wiktionary.org/)", e.name, e.code))
        .collect::<String>();
    let flags = lang
        .editions
        .iter()
        .map(|e| format!(" \\\n    --edition {}={}", e.code, e.file()))
        .collect::<String>();
    let urls = lang
        .editions
        .iter()
        .map(|e| format!("\n# {}: {}", e.name, e.url()))
        .collect::<String>();
    format!(
        "# {name}\n\n{intro}\n## How it works\n\n\
         This crate was generated by [flexion](https://github.com/gold-silver-copper/flexion) from a\n\
         description of {display} grammar and the Kaikki dumps of the English Wiktionary's{sources}\n\
         {display} entries.\n\
         For every part of speech, each attested word is reduced to its **inflection class**: the edits\n\
         (strip a suffix, add a suffix, maybe add a prefix, place the stress) that turn its lemma into\n\
         each of its forms. A suffix tree over lemmas, read from the last letter backwards, stores at\n\
         each node how likely each class is for words ending that way. Nodes that add nothing over\n\
         their parent are pruned; whole words survive only when they are real exceptions. To inflect a\n\
         word, the runtime walks it as deep as the tree goes and applies the most likely class that\n\
         fits. Words nobody wrote down get the patterns of the words that end like them; attested words\n\
         get their own forms.\n\n\
         Confidences are the tree's smoothed class probabilities. Where Wiktionary lists several\n\
         forms for one cell, each later-listed form gets half the weight of the one before, so\n\
         confidences between attested variants reflect Wiktionary's ordering, not measured usage.\n\n\
         {report}\n\
         ## Data and license\n\n\
         The code is MIT or Apache-2.0. The model (`src/model.bin`) is derived from\n\
         [the English Wiktionary](https://en.wiktionary.org/){links} via [Kaikki](https://kaikki.org/) and\n\
         [wiktextract](https://github.com/tatuylonen/wiktextract), and is licensed under\n\
         [CC BY-SA 4.0](https://creativecommons.org/licenses/by-sa/4.0/); see `DATA-LICENSE.md`.\n\n\
         ## Regenerating\n\n\
         ```sh{urls}\ncd flexion\ncargo xtask build {name} --dump kaikki.org-dictionary-{file}.jsonl{flags}\n```\n",
        name = lang.name,
        display = lang.display,
        file = lang.display.replace(' ', ""),
        intro = lang.readme_intro,
    )
}

