//! Per-form outcomes of a `try`, saved to a file (`--save`), and the paired
//! comparison of two saved runs (`compare`).

use flexion_train::eval::{Input, Outcome};
use flexion_train::extract::Lexeme;
use flexion_train::measure::{self, Paired};
use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::path::Path;

/// A name for how the words were typed, as saved.
pub fn mode(input: Input<'_>) -> String {
    match input {
        Input::Full => "full".into(),
        Input::Headword => "headword".into(),
        Input::Citation(_) => "principal-parts".into(),
        Input::Features => "features".into(),
        Input::Given(k) => format!("given-{k}"),
    }
}

/// Each scored word's name in a saved run: its key, and after a `#` its
/// place among the scored words with that key (homographs).
pub fn word_ids(words: &[&Lexeme]) -> Vec<String> {
    let mut seen: BTreeMap<&str, usize> = BTreeMap::new();
    words
        .iter()
        .map(|l| {
            let n = seen.entry(l.key.as_str()).or_default();
            *n += 1;
            format!("{}#{}", l.key, *n)
        })
        .collect()
}

/// Each scored word's group: its entry's kind (`own`, `form-of`, `alt-of`)
/// and whether it is a training word's root (`on`) or not (`new`), as
/// `own/new`.
pub fn groups(words: &[&Lexeme], on: &[bool]) -> Vec<String> {
    use flexion_train::extract::Of;
    words
        .iter()
        .zip(on)
        .map(|(l, &on)| {
            let of = match l.of {
                Of::Own => "own",
                Of::Form => "form-of",
                Of::Spelling => "alt-of",
            };
            format!("{of}/{}", if on { "on" } else { "new" })
        })
        .collect()
}

/// The scored words of a part of speech as saved: their names (see
/// [`word_ids`]), groups (see [`groups`]), and the cells' names.
pub struct Words<'a> {
    pub ids: &'a [String],
    pub groups: &'a [String],
    pub cells: &'a [String],
}

/// The rows of a run, as written: a header, then per form `part of speech,
/// mode, word, cell, right (1/0), the right answer's place (1 first; `-`
/// if no candidate), the first candidate's probability, the right
/// answer's, its bits, the word's group, the cell's name, what went wrong
/// if anything (see [`flexion_train::measure::Kind`]), and whether the
/// first answer is compatible with the length the dictionary states (1/0;
/// see [`flexion_train::eval::TableLength`])`, tab-separated.
#[derive(Debug, Default)]
pub struct Saved {
    text: String,
    /// Per part of speech and generated file, its bytes (see
    /// [`bytes_path`]).
    bytes: String,
}

/// Where a saved run keeps its parts' generated bytes: beside it, `.bytes`
/// added to its name.
pub fn bytes_path(path: &Path) -> std::path::PathBuf {
    let mut name = path.as_os_str().to_owned();
    name.push(".bytes");
    std::path::PathBuf::from(name)
}

const HEADER: &str =
    "pos\tmode\tword\tcell\tright\trank\ttop\tprobability\tbits\tgroup\tname\terror\tcompatible\n";

impl Saved {
    pub fn add(&mut self, pos: &str, mode: &str, words: &Words<'_>, outcomes: &[Outcome]) {
        for o in outcomes {
            let word = words.ids.get(o.word).map_or("?", String::as_str);
            let group = words.groups.get(o.word).map_or("?", String::as_str);
            let name = words.cells.get(o.cell).map_or("?", String::as_str);
            let rank = o.rank.map_or("-".to_string(), |r| (r + 1).to_string());
            let error = o.error.map_or(String::new(), |e| e.to_string());
            let _ = writeln!(
                self.text,
                "{pos}\t{mode}\t{word}\t{}\t{}\t{rank}\t{:.4}\t{:.4}\t{:.3}\t{group}\t{name}\t{error}\t{}",
                o.cell,
                u8::from(o.right()),
                o.top,
                o.probability,
                o.bits,
                u8::from(o.compatible)
            );
        }
    }

    /// Record what a part of speech's generated files take.
    pub fn add_bytes(&mut self, pos: &str, files: &[(String, usize)]) {
        for (file, n) in files {
            let _ = writeln!(self.bytes, "{pos}\t{file}\t{n}");
        }
    }

    pub fn write(&self, path: &Path) -> Result<(), String> {
        std::fs::write(path, format!("{HEADER}{}", self.text))
            .map_err(|e| format!("{}: {e}", path.display()))?;
        let bytes = bytes_path(path);
        std::fs::write(&bytes, format!("pos\tfile\tbytes\n{}", self.bytes))
            .map_err(|e| format!("{}: {e}", bytes.display()))
    }
}

/// A scored word: its group, if saved (see [`groups`]), and per cell
/// whether it is right and whether compatible with stated length (right,
/// in a run saved without it), with the cell's name if saved.
#[derive(Default)]
struct Scored {
    group: Option<String>,
    cells: BTreeMap<usize, (bool, bool, Option<String>)>,
}

/// A cell both runs scored: right in the first and in the second, whether
/// it is one of those `--apart` names, and compatible with stated length in
/// the first and in the second.
type Both = (bool, bool, bool, (bool, bool));

/// `(pos, mode)` → word → its scored cells.
type Run = BTreeMap<(String, String), BTreeMap<String, Scored>>;

fn read(path: &Path) -> Result<Run, String> {
    let text = std::fs::read_to_string(path).map_err(|e| format!("{}: {e}", path.display()))?;
    let mut run = Run::new();
    for line in text.lines().skip(1) {
        let f: Vec<&str> = line.split('\t').collect();
        let (Some(pos), Some(mode), Some(word), Some(cell), Some(right)) =
            (f.first(), f.get(1), f.get(2), f.get(3), f.get(4))
        else {
            continue;
        };
        let cell: usize = cell
            .parse()
            .map_err(|_| format!("{}: bad line {line}", path.display()))?;
        let scored = run
            .entry(((*pos).to_string(), (*mode).to_string()))
            .or_default()
            .entry((*word).to_string())
            .or_default();
        scored.group = f.get(9).map(|g| (*g).to_string());
        let name = f.get(10).map(|n| (*n).to_string());
        let right = *right == "1";
        let compatible = f.get(12).map_or(right, |c| *c == "1");
        scored.cells.insert(cell, (right, compatible, name));
    }
    Ok(run)
}

/// `cargo xtask compare <a> <b>`: per part of speech and mode, top-1 of
/// each run on the forms both scored, the paired bootstrap 95% interval of
/// b − a (resampling words), and the sign test over words.
pub fn compare(a: &Path, b: &Path, apart: Option<&str>) -> Result<(), String> {
    if a.is_dir() && b.is_dir() {
        return sweeps(a, b);
    }
    compare_bytes(a, b);
    let (ra, rb) = (read(a)?, read(b)?);
    println!(
        "{:<10} {:<16} {:<14} {:>6} {:>7} {:>8} {:>8} {:>8} {:>18} {:>11} {:>9}",
        "pos",
        "mode",
        "group",
        "words",
        "forms",
        "a",
        "b",
        "b − a",
        "95% interval",
        "better/worse",
        "sign p"
    );
    for (key, wa) in &ra {
        let Some(wb) = rb.get(key) else {
            continue;
        };
        // The words both scored, each with its group and the cells both
        // scored (the cells named `apart` marked).
        let mut words: Vec<(String, Vec<Both>)> = Vec::new();
        for (word, ca) in wa {
            let Some(cb) = wb.get(word) else {
                continue;
            };
            let group = cb.group.clone().or_else(|| ca.group.clone());
            let cells: Vec<Both> = (ca.cells.iter())
                .filter_map(|(cell, (x, cx, na))| {
                    let (y, cy, nb) = cb.cells.get(cell)?;
                    let name = nb.as_deref().or(na.as_deref()).unwrap_or("");
                    Some((*x, *y, apart.is_some_and(|p| name.contains(p)), (*cx, *cy)))
                })
                .collect();
            words.push((group.unwrap_or_else(|| "?".into()), cells));
        }
        let row = |label: &str, keep: &dyn Fn(&str, bool) -> bool, compatible: bool| {
            let paired: Vec<Paired> = (words.iter())
                .map(|(g, cells)| {
                    let mine = cells.iter().filter(|c| keep(g, c.2));
                    mine.fold(
                        Paired {
                            forms: 0,
                            a: 0,
                            b: 0,
                        },
                        |p, &(x, y, _, (cx, cy))| {
                            let (x, y) = if compatible { (cx, cy) } else { (x, y) };
                            Paired {
                                forms: p.forms + 1,
                                a: p.a + usize::from(x),
                                b: p.b + usize::from(y),
                            }
                        },
                    )
                })
                .filter(|p| p.forms > 0)
                .collect();
            if paired.is_empty() {
                return;
            }
            let c = measure::compare(&paired);
            println!(
                "{:<10} {:<16} {:<14} {:>6} {:>7} {:>7.2}% {:>7.2}% {:>+7.2} {:>+8.2} … {:>+6.2} {:>6}/{:<5} {:>9.2e}",
                key.0,
                key.1,
                label,
                c.words,
                c.forms,
                100.0 * c.a,
                100.0 * c.b,
                100.0 * (c.b - c.a),
                100.0 * c.low,
                100.0 * c.high,
                c.better,
                c.worse,
                c.p
            );
        };
        row("all", &|_, _| true, false);
        // A second score where a run has one: compatible with stated length.
        if words
            .iter()
            .flat_map(|(_, cells)| cells)
            .any(|&(x, y, _, (cx, cy))| x != cx || y != cy)
        {
            row("compatible", &|_, _| true, true);
        }
        if let Some(p) = apart {
            row(&format!("cells {p}"), &|_, a| a, false);
            row("other cells", &|_, a| !a, false);
        }
        let groups: std::collections::BTreeSet<&str> =
            words.iter().map(|(g, _)| g.as_str()).collect();
        if groups.len() > 1 {
            for group in groups {
                row(group, &|g, _| g == group, false);
            }
        }
    }
    Ok(())
}

/// Two sweeps (`cargo xtask sweep`): every language both have, compared as
/// two runs are, then each language's time and peak memory in b against a.
fn sweeps(a: &Path, b: &Path) -> Result<(), String> {
    let summary = |dir: &Path| -> BTreeMap<String, (f64, f64)> {
        std::fs::read_to_string(dir.join("summary.tsv"))
            .unwrap_or_default()
            .lines()
            .skip(1)
            .filter_map(|l| {
                let f: Vec<&str> = l.split('\t').collect();
                Some((
                    (*f.first()?).to_string(),
                    (f.get(1)?.parse().ok()?, f.get(2)?.parse().ok()?),
                ))
            })
            .collect()
    };
    let (sa, sb) = (summary(a), summary(b));
    for (lang, &(secs_a, peak_a)) in &sa {
        let file = format!("{lang}.tsv");
        let (fa, fb) = (a.join(&file), b.join(&file));
        let Some(&(secs_b, peak_b)) = sb.get(lang) else {
            continue;
        };
        println!(
            "\n{lang}: time {secs_a:.0}s → {secs_b:.0}s (×{:.2}), peak {peak_a:.0} → {peak_b:.0} MB (×{:.2})",
            secs_b / secs_a.max(1.0),
            peak_b / peak_a.max(1.0)
        );
        if fa.exists() && fb.exists() {
            compare(&fa, &fb, None)?;
        }
    }
    Ok(())
}

/// `(pos, file)` → bytes of a saved run's generated files, if it kept them.
fn read_bytes(path: &Path) -> BTreeMap<(String, String), usize> {
    std::fs::read_to_string(bytes_path(path))
        .unwrap_or_default()
        .lines()
        .skip(1)
        .filter_map(|l| {
            let f: Vec<&str> = l.split('\t').collect();
            Some((
                ((*f.first()?).to_string(), (*f.get(1)?).to_string()),
                f.get(2)?.parse().ok()?,
            ))
        })
        .collect()
}

/// Each part of speech's generated bytes in run a and run b, by file, where
/// they differ, and in all.
fn compare_bytes(a: &Path, b: &Path) {
    let (ba, bb) = (read_bytes(a), read_bytes(b));
    if ba.is_empty() || bb.is_empty() {
        return;
    }
    let keys: std::collections::BTreeSet<&(String, String)> = ba.keys().chain(bb.keys()).collect();
    let mut totals: BTreeMap<&str, (usize, usize)> = BTreeMap::new();
    println!(
        "{:<10} {:<16} {:>10} {:>10} {:>9}",
        "pos", "file", "a bytes", "b bytes", "b − a"
    );
    for key in keys {
        let (x, y) = (
            ba.get(key).copied().unwrap_or(0),
            bb.get(key).copied().unwrap_or(0),
        );
        let t = totals.entry(key.0.as_str()).or_default();
        *t = (t.0 + x, t.1 + y);
        if x != y {
            #[allow(clippy::cast_possible_wrap)]
            let d = y as i64 - x as i64;
            println!("{:<10} {:<16} {x:>10} {y:>10} {d:>+9}", key.0, key.1);
        }
    }
    for (pos, (x, y)) in totals {
        #[allow(clippy::cast_possible_wrap)]
        let d = y as i64 - x as i64;
        println!("{pos:<10} {:<16} {x:>10} {y:>10} {d:>+9}", "(all)");
    }
}
