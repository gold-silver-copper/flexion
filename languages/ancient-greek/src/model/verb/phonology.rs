//! The sound laws: edits carry trigger characters that set them off;
//! the last rule deletes any trigger left.

use flexion::sound_law::{Program, RuleSet, sound_laws};
use std::sync::OnceLock;

const LAWS: RuleSet<'static> = sound_laws! {
    classes {
        S0 = ["β", "γ", "γν", "γχ", "δ", "ζ", "θ", "κ", "κν", "μβ", "ν", "νν", "π", "πτ", "ρχ", "σκ", "σσ", "τ", "φ", "χ"];
        S1 = ["β", "γ", "ζ", "θ", "κ", "λ", "μν", "π", "πτ", "ρχ", "σ", "σσ", "ττ", "χ"];
        S2 = ["β", "γ", "δ", "ζ", "θ", "κ", "ν", "π", "πτ", "σσ", "ττ"];
        S3 = ["β", "δ", "ζ", "θ", "ν", "σσ", "χ"];
        S4 = ["γ", "ζ", "θ", "κ", "ν", "πτ", "σσ", "φ"];
        S5 = ["ζ", "πτ"];
        S6 = ["ζ", "πτ"];
        S7 = ["ζ", "κ"];
        S8 = ["β", "γ", "δ", "θ", "κ", "λ", "μ", "ν", "π", "σ", "τ", "φ", "χ"];
        TRIGGER = ["\u{e000}", "\u{e001}", "\u{e002}", "\u{e003}", "\u{e004}", "\u{e005}", "\u{e006}", "\u{e007}", "\u{e008}"];
    }
    maps {
        M0 = ["β" => "ψ", "γ" => "ξ", "γν" => "ξ", "γχ" => "χ", "δ" => "σ", "ζ" => "σ", "θ" => "σ", "κ" => "ξ", "κν" => "ξ", "μβ" => "β", "ν" => "σ", "νν" => "σ", "π" => "ψ", "πτ" => "ψ", "ρχ" => "λθ", "σκ" => "ξ", "σσ" => "ξ", "τ" => "ξ", "φ" => "ψ", "χ" => "ξ"];
        M1 = ["β" => "φθ", "γ" => "χθ", "ζ" => "σθ", "θ" => "σθ", "κ" => "χ", "λ" => "θ", "μν" => "τμ", "π" => "φθ", "πτ" => "φθ", "ρχ" => "λθ", "σ" => "θ", "σσ" => "χθ", "ττ" => "χ", "χ" => "σχ"];
        M2 = ["β" => "φ", "γ" => "χ", "δ" => "σ", "ζ" => "σ", "θ" => "σ", "κ" => "χ", "ν" => "σ", "π" => "φ", "πτ" => "φ", "σσ" => "χ", "ττ" => "χ"];
        M3 = ["β" => "ψ", "δ" => "σ", "ζ" => "σμ", "θ" => "σ", "ν" => "τ", "σσ" => "γμ", "χ" => "ξ"];
        M4 = ["γ" => "χθ", "ζ" => "σ", "θ" => "τ", "κ" => "χθ", "ν" => "σθ", "πτ" => "φ", "σσ" => "γ", "φ" => "π"];
        M5 = ["ζ" => "κ", "πτ" => "φ"];
        M6 = ["ζ" => "σ", "πτ" => "μ"];
        M7 = ["ζ" => "γ", "κ" => "γ"];
        M8 = ["β" => "β", "γ" => "γ", "δ" => "δ", "θ" => "τ", "κ" => "κ", "λ" => "λ", "μ" => "μ", "ν" => "ν", "π" => "π", "σ" => "σ", "τ" => "τ", "φ" => "π", "χ" => "κ"];
    }
    rules {
        end_0: "{x:S0}" => "{x|M0}" / "" _ "\u{e000}";
        end_1: "{x:S1}" => "{x|M1}" / "" _ "\u{e001}";
        end_2: "{x:S2}" => "{x|M2}" / "" _ "\u{e002}";
        end_3: "{x:S3}" => "{x|M3}" / "" _ "\u{e003}";
        end_4: "{x:S4}" => "{x|M4}" / "" _ "\u{e004}";
        end_5: "{x:S5}" => "{x|M5}" / "" _ "\u{e005}";
        end_6: "{x:S6}" => "{x|M6}" / "" _ "\u{e006}";
        end_7: "{x:S7}" => "{x|M7}" / "" _ "\u{e007}";
        start_8: "\u{e008}ε{x:S8}" => "{x|M8}ε{x}";
        cleanup: "{t:TRIGGER}" => "";
    }
};

pub(crate) fn program() -> Option<&'static Program> {
    static PROGRAM: OnceLock<Option<Program>> = OnceLock::new();
    PROGRAM.get_or_init(|| LAWS.compile().ok()).as_ref()
}
