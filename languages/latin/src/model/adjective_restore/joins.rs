/// Per join class, one edit per cell (`u16::MAX`: no form).
static CLASSES: [[u16; 1]; 1] = [
    [u16::MAX],
];

pub(crate) fn edit(class: usize, cell: usize) -> Option<u32> {
    let e = *CLASSES.get(class)?.get(cell)?;
    Some(if e == u16::MAX { NONE } else { u32::from(e) })
}
